// Builds cmd's icons from Phosphor (MIT, phosphoricons.com), the one icon set every
// part of cmd draws with:
//   ../src/icons.gen.ts              every icon's name and its codepoint in the fonts, and IconName
//   ../src/fonts/phosphor-*.woff2    the fonts, one per weight the kit offers (icon.tsx)
//   protocol/src/icons.gen.ts        the names alone, so the core can check a name it's given
//                                    (a workspace's icon, a widget's manifest)
// Run `pnpm symbols` after updating @phosphor-icons/core or /web; `pnpm symbols --check`
// (and a test) fails when the generated files are stale.

import fs from "node:fs";
import path from "node:path";
import { icons } from "@phosphor-icons/core";

const DIR = import.meta.dirname;
const OUT_TS = path.join(DIR, "../src/icons.gen.ts");
const OUT_FONTS = path.join(DIR, "../src/fonts");
const OUT_NAMES = path.join(DIR, "../../protocol/src/icons.gen.ts");

/** The kit's weights → the web package's fonts. */
export const FONTS = { regular: "regular/Phosphor.woff2", light: "light/Phosphor-Light.woff2", bold: "bold/Phosphor-Bold.woff2", fill: "fill/Phosphor-Fill.woff2" } as const;

// Neither package exports its package.json or fonts, so they're read from the kit's node_modules.
const pkgDir = (pkg: string) => path.join(DIR, "../node_modules", pkg);
const version = (pkg: string) => (JSON.parse(fs.readFileSync(path.join(pkgDir(pkg), "package.json"), "utf8")) as { version: string }).version;
const webSrc = () => path.join(pkgDir("@phosphor-icons/web"), "src");

const header = (what: string) => `// Generated by \`pnpm symbols\` (packages/ui/icons/build.ts) from @phosphor-icons/core ${version("@phosphor-icons/core")}: ${what}. Don't edit.\n\n`;

/** Several entries to a line, so the files stay short to read. */
function lines(items: string[], per: number): string {
  const out: string[] = [];
  for (let i = 0; i < items.length; i += per) out.push(`  ${items.slice(i, i + per).join(" ")}`);
  return out.join("\n");
}

export function build(): { ts: string; names: string } {
  const sorted = [...icons].sort((a, b) => (a.name < b.name ? -1 : 1));
  const ts =
    header("every icon and its codepoint in the Phosphor fonts") +
    `/** Every Phosphor icon by name → its codepoint in the fonts (phosphoricons.com shows them all). */\n` +
    `export const ICONS = {\n${lines(
      sorted.map((i) => `"${i.name}": 0x${i.codepoint.toString(16)},`),
      6,
    )}\n} as const;\n\n/** A Phosphor icon's name ("house", "caret-down", "terminal-window"). */\nexport type IconName = keyof typeof ICONS;\n`;
  const names =
    header("the icons' names") +
    `/** Every Phosphor icon's name: what workspaces and widgets may name as their icon. */\n` +
    `export const ICON_NAMES: ReadonlySet<string> = new Set(\n  \`\n${lines(
      sorted.map((i) => i.name),
      8,
    )}\n\`\n    .trim()\n    .split(/\\s+/),\n);\n`;
  return { ts, names };
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const { ts, names } = build();
  const stale: string[] = [];
  const write = (file: string, body: string | Buffer) => {
    const same = fs.existsSync(file) && Buffer.compare(fs.readFileSync(file), Buffer.from(body)) === 0;
    if (same) return;
    if (check) stale.push(path.relative(process.cwd(), file));
    else fs.mkdirSync(path.dirname(file), { recursive: true }), fs.writeFileSync(file, body);
  };
  write(OUT_TS, ts);
  write(OUT_NAMES, names);
  for (const [weight, src] of Object.entries(FONTS)) write(path.join(OUT_FONTS, `phosphor-${weight}.woff2`), fs.readFileSync(path.join(webSrc(), src)));
  if (stale.length) {
    console.error(`stale, run pnpm symbols: ${stale.join(", ")}`);
    process.exit(1);
  }
}
