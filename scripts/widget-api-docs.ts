// `pnpm widget-api:docs`: the reference section of packages/widget-api/README.md, generated
// from the API's own d.ts with the TypeScript compiler (docs/56, "The API reference"): one
// section per `cmd` namespace with each verb's signature, @since and permission, the hooks,
// and one section per element of API_ELEMENTS with its props. A verb's Since and Permission
// are its row in protocol widget-verbs.ts's API (a hook's or use()'s, its topic's verb's), the
// row the core enforces, so the page and the core can't drift; frame pages' `cmd` comes from
// src/frame.ts's FrameCmd (@cmd/widget-api/frame); contract.test.ts holds the
// JSDoc's @since and "Needs" to the same rows. The same reference, with how to start, is the website's widgets
// page (website/public/_lib/widget-api.html, in the site's layout by widgets/index.php).
// packages/widget-api/test/docs.test.ts fails when either is stale.
//
//   node scripts/widget-api-docs.ts           write the README's reference
//   node scripts/widget-api-docs.ts --check   exit 1 when it is stale

import fs from "node:fs";
import path from "node:path";
import ts from "typescript";
import { API as VERBS, API_ELEMENTS, WIDGET_API, WIDGET_API_MINOR, isShape, topicVerb, type ApiElementSpec, type ApiVerbSpec } from "../packages/protocol/src/widget-tree.ts";

/** A verb's row by its name ("agents.list"), or undefined. */
const rowOf = (verb: string): ApiVerbSpec | undefined => (VERBS as Record<string, ApiVerbSpec>)[verb];

const root = path.resolve(import.meta.dirname, "..");
const API = path.join(root, "packages/widget-api");
export const README = path.join(API, "README.md");
const START = "<!-- reference:start (generated by pnpm widget-api:docs from the JSDoc in src/: edit those, not this) -->";
const END = "<!-- reference:end -->";

/** The exports of @cmd/widget-api (src/index.ts) as the checker sees them, aliases resolved: what contract.test.ts checks and this page documents. */
export function apiExports(dir = API): { checker: ts.TypeChecker; exported: ts.Symbol[] } {
  const entry = path.join(dir, "src/index.ts");
  const program = ts.createProgram([entry], { module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext, jsx: ts.JsxEmit.ReactJSX, allowImportingTsExtensions: true, noEmit: true, strict: true, types: ["node"] });
  const checker = program.getTypeChecker();
  const index = checker.getSymbolAtLocation(program.getSourceFile(entry)!)!;
  const exported = checker.getExportsOfModule(index).map((s) => (s.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(s) : s));
  return { checker, exported };
}

const one = (s: string) => s.replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|").trim();
const code = (s: string) => "`" + s.replace(/\s+/g, " ").replace(/\|/g, "\\|") + "`";

/** What a row needs, as package.json's cmd.permissions writes it (`ns`: the verb's namespace, for an act). */
function permission(row: ApiVerbSpec | undefined, ns = ""): string {
  if (!row) return "none";
  const media = row.mode === "read" ? "read" : "control";
  const base = ({ workspace: '`workspace: ["read"]`', events: "`events: [<class>]`", net: "`net: [<host>]`", ai: '`ai: ["complete"]`', act: `\`act: ["${ns}"]\``, run: "`run: [<program>]`", media: `\`media: ["${media}"]\`` } as Record<string, string>)[row.needs ?? ""] ?? "none";
  // A read that also needs a class of events (journal.days: agents).
  const cls = (row as { class?: string }).class;
  const need = cls ? `${base}, \`events: ["${cls}"]\`` : base;
  return row.mode === "read" ? need : `${need}, ${row.mode === "act" ? "acts" : "asks"}`;
}

/** The reference, as Markdown. */
export function reference(): string {
  const { checker, exported } = apiExports();
  const doc = (s: ts.Symbol) => one(ts.displayPartsToString(s.getDocumentationComment(checker)));
  const since = (s: ts.Symbol) => ts.displayPartsToString(s.getJsDocTags(checker).find((t) => t.name === "since")?.text ?? []).trim() || "1.0";
  const sig = (s: ts.Symbol, name: string) => {
    const t = checker.getTypeOfSymbol(s);
    const call = t.getCallSignatures()[0];
    if (!call) return checker.typeToString(t);
    const text = checker.signatureToString(call, undefined, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.WriteArrowStyleSignature);
    // A verb is typed from the protocol's tuple of params: show them as parameters.
    return name + text.replace(/^(<[^>]*>)?\(\.\.\.args: \[(.*)\]\)/, (_, g = "", p) => `${g}(${p})`).replace(/^(<[^>]*>)?\((.*?)\) => /, (_, g = "", p) => `${g}(${p}): `);
  };
  const find = (name: string) => exported.find((s) => s.name === name);
  const out: string[] = [START, "", "## Reference", "", `API ${WIDGET_API}, minor ${WIDGET_API_MINOR}. Everything here is in API ${WIDGET_API} for good; what came after 1.0 says \`@since 1.x\`, and a widget that also runs on an older cmd checks \`cmd.env.has(name)\` first (a verb or an element).`, ""];

  out.push("### `cmd`", "", doc(find("cmd")!), "");
  for (const ns of checker.getTypeOfSymbol(find("cmd")!).getProperties()) {
    out.push(`#### \`cmd.${ns.name}\``, "", doc(ns), "", "| Verb | Since | Permission | What |", "|---|---|---|---|");
    // A namespace that is also a function (cmd.run): its call first, documented on the call signature.
    const call = checker.getTypeOfSymbol(ns).getCallSignatures()[0];
    if (call) {
      const text = checker.signatureToString(call, undefined, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.WriteArrowStyleSignature).replace(/^\((.*?)\) => /, "($1): ");
      const tag = call.getJsDocTags().find((t) => t.name === "since");
      const row = rowOf(`${ns.name}.exec`);
      out.push(`| ${code(`cmd.${ns.name}${text}`)} | ${row?.since ?? (ts.displayPartsToString(tag?.text ?? []).trim() || "1.0")} | ${permission(row)} | ${one(ts.displayPartsToString(call.getDocumentationComment(checker)))} |`);
    }
    for (const m of checker.getTypeOfSymbol(ns).getProperties()) {
      const verb = `${ns.name}.${m.name}`;
      // An object of methods (cmd.storage.window, a Store): each method, under its whole name.
      const mt = checker.getTypeOfSymbol(m);
      if (!mt.getCallSignatures().length && mt.getProperties().some((x) => checker.getTypeOfSymbol(x).getCallSignatures().length)) {
        out.push(`| ${code(`cmd.${verb}`)} | ${since(m)} | none | ${doc(m)} |`);
        for (const x of mt.getProperties()) out.push(`| ${code(sig(x, `cmd.${verb}.${x.name}`))} | ${since(x)} | none | ${doc(x)} |`);
        continue;
      }
      const own = rowOf(verb);
      const row = own ?? (m.name === "use" || m.name === "subscribe" ? rowOf(topicVerb(ns.name) ?? `${ns.name}.complete`) : undefined);
      out.push(`| ${code(sig(m, `cmd.${verb}`))} | ${own?.since ?? since(m)} | ${ns.name === "fmt" ? "none" : permission(row, ns.name)} | ${doc(m)} |`);
    }
    out.push("");
  }

  out.push("### Hooks", "", "The reads as subscriptions: each gets the current value at once and every change after, until its component unmounts.", "", "| Hook | Since | What |", "|---|---|---|");
  for (const s of exported.filter((x) => /^use[A-Z]/.test(x.name)).sort((a, b) => a.name.localeCompare(b.name))) out.push(`| ${code(sig(s, s.name))} | ${since(s)} | ${doc(s)} |`);
  out.push("", `${code(sig(find("defineWidget")!, "defineWidget"))}: ${doc(find("defineWidget")!)}`, "");

  out.push(...frames(), "");

  out.push("### Elements", "", "The app draws each with its kit; a tree can name nothing else. Handlers (`onClick`, a menu entry's `run`) are functions in the widget and ids on the wire.", "");
  for (const name of Object.keys(API_ELEMENTS)) {
    const el = find(name);
    const props = find(`${name}Props`);
    out.push(`#### \`${name}\``, "", el ? `${doc(el)}${since(el) === "1.0" ? "" : ` Since ${since(el)}.`}` : "", "");
    const list = props ? checker.getDeclaredTypeOfSymbol(props).getProperties() : [];
    if (!list.length) {
      out.push("No props.", "");
      continue;
    }
    out.push("| Prop | Type | What |", "|---|---|---|");
    for (const p of list) {
      const d = p.valueDeclaration ?? p.declarations?.[0];
      const type = d && ts.isPropertySignature(d) && d.type ? d.type.getText() : checker.typeToString(checker.getTypeOfSymbol(p));
      out.push(`| \`${p.name}\`${p.flags & ts.SymbolFlags.Optional ? "" : " (required)"} | ${code(type)} | ${doc(p)} |`);
    }
    out.push("");
  }
  // The records props hold (1.2): their fields, once each.
  const shapes = [...new Set((Object.values(API_ELEMENTS) as ApiElementSpec[]).flatMap((e) => [...Object.values(e.props).map((p) => p.type), ...Object.values(e.events).map((x) => x.value)]).flatMap((t) => (t && isShape(t) ? [t.name] : [])))];
  if (shapes.length) out.push("### Records", "", "What the charts' and DataGrid's props hold: plain values, a field each.", "");
  for (const name of shapes) {
    const s = find(name)!;
    out.push(`#### \`${name}\``, "", `${doc(s)} Since ${since(s)}.`, "", "| Field | Type | What |", "|---|---|---|");
    for (const p of checker.getDeclaredTypeOfSymbol(s).getProperties()) {
      const d = p.valueDeclaration ?? p.declarations?.[0];
      const type = d && ts.isPropertySignature(d) && d.type ? d.type.getText() : checker.typeToString(checker.getTypeOfSymbol(p));
      out.push(`| \`${p.name}\`${p.flags & ts.SymbolFlags.Optional ? "" : " (required)"} | ${code(type)} | ${doc(p)} |`);
    }
    out.push("");
  }
  out.push(END);
  return out.join("\n");
}

/**
 * The section on frames: what a frame widget's page has (src/frame.ts's FrameCmd, the types of
 * `@cmd/widget-api/frame`): the verbs as above, each live topic's subscribe, and the page's own.
 */
function frames(): string[] {
  const entry = path.join(API, "src/frame.ts");
  const program = ts.createProgram([entry], { module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext, jsx: ts.JsxEmit.ReactJSX, allowImportingTsExtensions: true, noEmit: true, strict: true, types: ["node"] });
  const checker = program.getTypeChecker();
  const mod = checker.getSymbolAtLocation(program.getSourceFile(entry)!)!;
  const frameCmd = checker.getExportsOfModule(mod).find((x) => x.name === "FrameCmd")!;
  const doc = (x: ts.Symbol) => one(ts.displayPartsToString(x.getDocumentationComment(checker)));
  const flags = ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.WriteArrowStyleSignature;
  const props = checker.getDeclaredTypeOfSymbol(frameCmd).getProperties();
  const live = props.filter((p) => checker.getTypeOfSymbol(p).getProperty("subscribe"));
  const namespaces = new Set(Object.keys(VERBS).map((v) => v.split(".")[0]!));
  const own = props.filter((p) => !live.includes(p) && (!namespaces.has(p.name) || p.name === "state"));
  const sub = checker.getTypeOfSymbol(live[0]!).getProperty("subscribe")!;
  /** `<T>(a: A, b?: B): R`, built from its parts (a function-typed parameter keeps its arrow). */
  const call = (c: ts.Signature) => {
    const tps = c.getTypeParameters()?.map((t) => checker.typeToString(t, undefined, flags)) ?? [];
    const ps = c.getParameters().map((p) => {
      const d = p.valueDeclaration;
      const opt = !!d && ts.isParameter(d) && !!d.questionToken;
      const t = opt ? checker.getNonNullableType(checker.getTypeOfSymbol(p)) : checker.getTypeOfSymbol(p);
      const text = checker.typeToString(t, undefined, flags);
      // A verb's params are the protocol's tuple: shown as the parameters they are.
      if (d && ts.isParameter(d) && d.dotDotDotToken && /^\[.*\]$/.test(text)) return text.slice(1, -1).replace(/\?: (.*?) \| undefined(?=,|$)/g, "?: $1");
      return `${p.name}${opt ? "?" : ""}: ${text}`;
    });
    return `${tps.length ? `<${tps.join(", ")}>` : ""}(${ps.join(", ")}): ${checker.typeToString(c.getReturnType(), undefined, flags)}`;
  };
  const out = [
    "### Frames",
    "",
    "A frame widget's page (`\"surface\": \"frame\"`, its `view.html`) has a `cmd` of its own, typed by `@cmd/widget-api/frame` (`/// <reference types=\"@cmd/widget-api/frame\" />`): every verb above, by the same name and with the same permissions, limits and asks; no hooks. A verb that needs a press (an act, `windows.open`) works right after a click in the frame, once per click. The page has no network of its own: its data comes through `cmd`.",
    "",
    "| Member | What |",
    "|---|---|",
    `| ${code(`cmd.<${live.map((p) => p.name).join(" | ")}>.subscribe(query?, fn, onError?): () => void`)} | ${doc(sub)} |`,
  ];
  // A live namespace's scopes with keys of their own (cmd.storage.window): their subscribe.
  for (const p of live)
    for (const q of checker.getTypeOfSymbol(p).getProperties()) {
      const s = checker.getTypeOfSymbol(q).getProperty("subscribe");
      if (s) out.push(`| ${code(`cmd.${p.name}.${q.name}.subscribe${call(checker.getTypeOfSymbol(s).getCallSignatures()[0]!)}`)} | ${doc(s)} |`);
    }
  for (const p of own) {
    const t = checker.getTypeOfSymbol(p);
    const calls = t.getCallSignatures();
    const methods = t.flags & ts.TypeFlags.Object ? t.getProperties().filter((m) => checker.getTypeOfSymbol(m).getCallSignatures().length) : [];
    if (calls.length) for (const c of calls) out.push(`| ${code(`cmd.${p.name}${call(c)}`)} | ${one(ts.displayPartsToString(c.getDocumentationComment(checker))) || doc(p)} |`);
    else if (!methods.length || p.name === "config") out.push(`| ${code(`cmd.${p.name}: ${checker.typeToString(t, undefined, flags)}`)} | ${doc(p)} |`);
    else for (const m of methods) out.push(`| ${code(`cmd.${p.name}.${m.name}${call(checker.getTypeOfSymbol(m).getCallSignatures()[0]!)}`)} | ${doc(m) || doc(p)} |`);
  }
  return out;
}

// ── the website (website/public/widgets/, docs/56 phase 3) ─────────────

/** The reference page's body on the website: website/public/widgets/index.php puts it in the site's layout. */
export const WEBSITE = path.join(root, "website/public/_lib/widget-api.html");

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
/** One line of the reference's Markdown: `code` (with \| inside), **bold**, the rest escaped. */
const inline = (s: string) =>
  s
    .split(/(`[^`]*`)/)
    .map((part) => (part.startsWith("`") && part.endsWith("`") && part.length > 1 ? `<code>${esc(part.slice(1, -1).replace(/\\\|/g, "|"))}</code>` : esc(part.replace(/\\\|/g, "|")).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")))
    .join("");
const slug = (s: string) => s.replace(/<[^>]+>|`/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/** The reference's Markdown (headings, paragraphs, tables, as reference() writes them) as HTML; headings get ids. */
export function referenceHtml(md: string): string {
  const out: string[] = [];
  let table: string[][] | null = null;
  const flush = () => {
    if (!table) return;
    const [head, , ...rows] = table;
    out.push(`<div class="api-table"><table><thead><tr>${head!.map((c) => `<th>${inline(c)}</th>`).join("")}</tr></thead><tbody>`);
    for (const r of rows) out.push(`<tr>${r.map((c) => `<td>${inline(c)}</td>`).join("")}</tr>`);
    out.push("</tbody></table></div>");
    table = null;
  };
  for (const line of md.split("\n")) {
    if (line.startsWith("<!--")) continue;
    if (line.startsWith("|")) {
      const cells = line.slice(1, line.endsWith("|") ? -1 : undefined).split(/(?<!\\)\|/).map((c) => c.trim());
      (table ??= []).push(cells);
      continue;
    }
    flush();
    const h = /^(#{2,4}) (.*)$/.exec(line);
    if (h) {
      const level = h[1]!.length;
      out.push(`<h${level} id="${slug(h[2]!)}">${inline(h[2]!)}</h${level}>`);
    } else if (line.trim()) out.push(`<p>${inline(line)}</p>`);
  }
  flush();
  return out.join("\n");
}

/** The page: how to start, then the reference, with a contents line per namespace. */
export function websitePage(ref = reference()): string {
  const namespaces = [...ref.matchAll(/^#### `(cmd\.[a-z]+)`$/gm)].map((m) => m[1]!);
  return [
    "<!-- generated by pnpm widget-api:docs (scripts/widget-api-docs.ts) from @cmd/widget-api's JSDoc: edit those, not this -->",
    "<h1>Widgets</h1>",
    '<p class="lede">A cmd widget is a small package: React made of cmd\'s own elements, reading your agents, terminals and windows live. It draws like a built-in window, asks before it reaches anything, and is tested without a browser.</p>',
    '<h2 id="start">Make one</h2>',
    "<pre><code>cmd widget new my-widget       # a package with a widget, its test, its story, CLAUDE.md\ncd my-widget\ncmd widget dev                 # on the board, its console here; saves reload it\nnpm test                       # or cmd widget test\ncmd widget check               # package.json, permissions, types\ncmd widget preview . --themes all --sizes all</code></pre>",
    "<p>Or ask Magic for one: it writes the same kind of package. Agents working in a package read its <code>CLAUDE.md</code> and this reference, which <code>cmd widget new</code> links at <code>node_modules/@cmd/widget-api/README.md</code>.</p>",
    `<p class="api-toc">${["cmd", ...namespaces, "Hooks", "Frames", "Elements", "Records"].map((n) => `<a href="#${slug(n === "cmd" ? "`cmd`" : n)}"><code>${esc(n)}</code></a>`).join(" · ")}</p>`,
    referenceHtml(ref.replace(/^## Reference$/m, "")),
    "",
  ].join("\n");
}

/** The README with `ref` as its reference section (appended when it has none). */
export function withReference(readme: string, ref: string): string {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  return a >= 0 && b > a ? readme.slice(0, a) + ref + readme.slice(b + END.length) : readme.trimEnd() + "\n\n" + ref + "\n";
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const ref = reference();
  const now = fs.readFileSync(README, "utf8");
  const next = withReference(now, ref);
  const page = websitePage(ref);
  const pageNow = fs.existsSync(WEBSITE) ? fs.readFileSync(WEBSITE, "utf8") : "";
  if (process.argv.includes("--check")) {
    if (now !== next) (console.error("packages/widget-api/README.md is stale: pnpm widget-api:docs"), process.exit(1));
    if (pageNow !== page) (console.error("website/public/_lib/widget-api.html is stale: pnpm widget-api:docs"), process.exit(1));
  } else {
    for (const [file, was, text] of [[README, now, next], [WEBSITE, pageNow, page]] as const) {
      if (was === text) console.log(`${path.relative(root, file)} is up to date`);
      else (fs.writeFileSync(file, text), console.log(`wrote ${path.relative(root, file)}`));
    }
  }
}
