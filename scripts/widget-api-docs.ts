// `pnpm widget-api:docs`: the reference section of packages/widget-api/README.md, generated
// from the API's own d.ts with the TypeScript compiler (docs/56, "The API reference"): one
// section per `cmd` namespace with each verb's signature, @since and permission, the hooks,
// and one section per element of API_ELEMENTS with its props. The permission is the core's
// own row (widgets/api/access.ts's API_ACCESS and TOPIC_ACCESS), so the page and what the
// core enforces can't drift. packages/widget-api/test/docs.test.ts fails when the README is stale.
//
//   node scripts/widget-api-docs.ts           write the README's reference
//   node scripts/widget-api-docs.ts --check   exit 1 when it is stale

import fs from "node:fs";
import path from "node:path";
import ts from "typescript";
import { API_ELEMENTS } from "../packages/protocol/src/widget-tree.ts";
import { API_ACCESS, TOPIC_ACCESS, type AccessRow } from "../packages/core/src/widgets/api/access.ts";

const root = path.resolve(import.meta.dirname, "..");
const API = path.join(root, "packages/widget-api");
export const README = path.join(API, "README.md");
const START = "<!-- reference:start (generated by pnpm widget-api:docs from the JSDoc in src/: edit those, not this) -->";
const END = "<!-- reference:end -->";

/** The exports of @cmd/widget-api (src/index.ts) as the checker sees them, aliases resolved: what contract.test.ts checks and this page documents. */
export function apiExports(dir = API): { checker: ts.TypeChecker; exported: ts.Symbol[] } {
  const entry = path.join(dir, "src/index.ts");
  const program = ts.createProgram([entry], { module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext, jsx: ts.JsxEmit.ReactJSX, allowImportingTsExtensions: true, noEmit: true, strict: true, types: ["node"] });
  const checker = program.getTypeChecker();
  const index = checker.getSymbolAtLocation(program.getSourceFile(entry)!)!;
  const exported = checker.getExportsOfModule(index).map((s) => (s.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(s) : s));
  return { checker, exported };
}

const one = (s: string) => s.replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|").trim();
const code = (s: string) => "`" + s.replace(/\s+/g, " ").replace(/\|/g, "\\|") + "`";

/** What a row needs, as package.json's cmd.permissions writes it. */
function permission(row: AccessRow | undefined): string {
  if (!row) return "none";
  const need = ({ workspace: '`workspace: ["read"]`', events: "`events: [<class>]`", net: "`net: [<host>]`", ai: '`ai: ["complete"]`' } as Record<string, string>)[row.needs ?? ""] ?? "none";
  return row.mode === "read" ? need : `${need}, ${row.mode === "act" ? "acts" : "asks each time"}`;
}

/** The reference, as Markdown. */
export function reference(): string {
  const { checker, exported } = apiExports();
  const doc = (s: ts.Symbol) => one(ts.displayPartsToString(s.getDocumentationComment(checker)));
  const since = (s: ts.Symbol) => ts.displayPartsToString(s.getJsDocTags(checker).find((t) => t.name === "since")?.text ?? []).trim() || "1.0";
  const sig = (s: ts.Symbol, name: string) => {
    const t = checker.getTypeOfSymbol(s);
    const call = t.getCallSignatures()[0];
    if (!call) return checker.typeToString(t);
    const text = checker.signatureToString(call, undefined, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.WriteArrowStyleSignature);
    // A verb is typed from the protocol's tuple of params: show them as parameters.
    return name + text.replace(/^(<[^>]*>)?\(\.\.\.args: \[(.*)\]\)/, (_, g = "", p) => `${g}(${p})`).replace(/^(<[^>]*>)?\((.*?)\) => /, (_, g = "", p) => `${g}(${p}): `);
  };
  const find = (name: string) => exported.find((s) => s.name === name);
  const out: string[] = [START, "", "## Reference", "", "API 1, minor 0. Everything here is in API 1 for good; what comes later says `@since 1.x`.", ""];

  out.push("### `cmd`", "", doc(find("cmd")!), "");
  for (const ns of checker.getTypeOfSymbol(find("cmd")!).getProperties()) {
    out.push(`#### \`cmd.${ns.name}\``, "", doc(ns), "", "| Verb | Since | Permission | What |", "|---|---|---|---|");
    for (const m of checker.getTypeOfSymbol(ns).getProperties()) {
      const verb = `${ns.name}.${m.name}`;
      const row = (API_ACCESS as Record<string, AccessRow>)[verb] ?? (m.name === "use" || m.name === "subscribe" ? (TOPIC_ACCESS as Record<string, AccessRow>)[ns.name] ?? (API_ACCESS as Record<string, AccessRow>)[`${ns.name}.complete`] : undefined);
      out.push(`| ${code(sig(m, `cmd.${verb}`))} | ${since(m)} | ${ns.name === "fmt" ? "none" : permission(row)} | ${doc(m)} |`);
    }
    out.push("");
  }

  out.push("### Hooks", "", "The reads as subscriptions: each gets the current value at once and every change after, until its component unmounts.", "", "| Hook | Since | What |", "|---|---|---|");
  for (const s of exported.filter((x) => /^use[A-Z]/.test(x.name)).sort((a, b) => a.name.localeCompare(b.name))) out.push(`| ${code(sig(s, s.name))} | ${since(s)} | ${doc(s)} |`);
  out.push("", `${code(sig(find("defineWidget")!, "defineWidget"))}: ${doc(find("defineWidget")!)}`, "");

  out.push("### Elements", "", "The app draws each with its kit; a tree can name nothing else. Handlers (`onClick`, a menu entry's `run`) are functions in the widget and ids on the wire.", "");
  for (const name of Object.keys(API_ELEMENTS)) {
    const el = find(name);
    const props = find(`${name}Props`);
    out.push(`#### \`${name}\``, "", el ? doc(el) : "", "");
    const list = props ? checker.getDeclaredTypeOfSymbol(props).getProperties() : [];
    if (!list.length) {
      out.push("No props.", "");
      continue;
    }
    out.push("| Prop | Type | What |", "|---|---|---|");
    for (const p of list) {
      const d = p.valueDeclaration ?? p.declarations?.[0];
      const type = d && ts.isPropertySignature(d) && d.type ? d.type.getText() : checker.typeToString(checker.getTypeOfSymbol(p));
      out.push(`| \`${p.name}\`${p.flags & ts.SymbolFlags.Optional ? "" : " (required)"} | ${code(type)} | ${doc(p)} |`);
    }
    out.push("");
  }
  out.push(END);
  return out.join("\n");
}

/** The README with `ref` as its reference section (appended when it has none). */
export function withReference(readme: string, ref: string): string {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  return a >= 0 && b > a ? readme.slice(0, a) + ref + readme.slice(b + END.length) : readme.trimEnd() + "\n\n" + ref + "\n";
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const now = fs.readFileSync(README, "utf8");
  const next = withReference(now, reference());
  if (process.argv.includes("--check")) {
    if (now !== next) (console.error("packages/widget-api/README.md is stale: pnpm widget-api:docs"), process.exit(1));
  } else if (now !== next) {
    fs.writeFileSync(README, next);
    console.log("wrote packages/widget-api/README.md's reference");
  } else console.log("packages/widget-api/README.md is up to date");
}
